import pytest

from device_bridges.bambu_autoejection import (
    BambuGcodeAutoejectionPatcher,
    BambuGcodeAutoejectionValidator,
)


BASE_GCODE = """; generated by Bambu Studio
; filament start gcode
G90
G1 X10.0 Y20.0 Z0.2 E0.03 F1200
G1 X40.0 Y55.0 Z10.0 E2.50 F1800
M104 S0
M140 S0
M84
"""


def test_plain_gcode_patch_inserts_single_validated_bambu_ejection_tail(tmp_path: Path) -> None:
    source = tmp_path / "specimen.gcode"
    source.write_text(BASE_GCODE, encoding="utf-8")
    patcher = BambuGcodeAutoejectionPatcher(output_dir=tmp_path / "patched")

    result = patcher.patch_artifact(source, specimen_id="specimen-cand-1", position="center")

    patched_path = Path(result["patched_artifact_path"])
    patched_text = patched_path.read_text(encoding="utf-8")
    assert result["ok"] is True
    assert result["source_plate_path"] == "plain_gcode"
    assert patched_path.name == "specimen.autoeject.gcode"
    assert patched_text.count("atr.bambu.autoejection.v1") == 1
    assert "; atr_source_sha256=" in patched_text
    assert "M190 R40" in patched_text
    assert patched_text.index("atr.bambu.autoejection.v1") < patched_text.rindex("M84")
    assert result["validation"]["ok"] is True
    assert result["object_bounds_mm"]["min_x"] == 10.0
    assert result["object_bounds_mm"]["max_y"] == 55.0
    assert result["patched_sha256"] == hashlib.sha256(patched_path.read_bytes()).hexdigest()


