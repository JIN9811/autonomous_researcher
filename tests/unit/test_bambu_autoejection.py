@pytest.mark.parametrize(
    ("position", "expected_x"),
    [
        ("left", "G0 X48.000"),
        ("center", "G0 X128.000"),
        ("right", "G0 X208.000"),
    ],
)
def test_standalone_ejection_artifact_generates_position_specific_valid_gcode(
    tmp_path: Path, position: str, expected_x: str
) -> None:
    patcher = BambuGcodeAutoejectionPatcher(output_dir=tmp_path / "patched")

    result = patcher.build_standalone_ejection_artifact(
        position=position,
        specimen_id=f"eject-{position}-test",
        object_size_mm=[30.0, 30.0, 20.0],
    )

    artifact_path = Path(result["patched_artifact_path"])
    startable_path = Path(result["startable_artifact_path"])
    gcode = artifact_path.read_text(encoding="utf-8")
    assert result["ok"] is True
    assert result["tool"] == "printer.bambu.autoejection_standalone"
    assert artifact_path.name == f"eject-{position}-test.{position}.autoeject.gcode"
    assert startable_path.name == f"eject-{position}-test.{position}.autoeject.gcode.3mf"
    assert result["startable_plate_path"] == "Metadata/plate_1.gcode"
    assert gcode.count("atr.bambu.autoejection.v1") == 1
    assert f"atr_position={position}" in gcode
    assert "M190 R40" in gcode
    assert expected_x in gcode
    assert result["validation"]["ok"] is True
    with zipfile.ZipFile(startable_path) as archive:
        plate_gcode = archive.read("Metadata/plate_1.gcode").decode("utf-8")
    assert "atr.bambu.autoejection.v1" in plate_gcode
    assert f"atr_position={position}" in plate_gcode


