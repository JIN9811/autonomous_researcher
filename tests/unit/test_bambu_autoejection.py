def test_plain_gcode_patch_is_idempotent_for_already_autoeject_artifact(tmp_path: Path) -> None:
    source = tmp_path / "specimen.gcode"
    source.write_text(BASE_GCODE, encoding="utf-8")
    patcher = BambuGcodeAutoejectionPatcher(output_dir=tmp_path / "patched")
    first = patcher.patch_artifact(source, specimen_id="specimen-cand-1", position="center")

    second = patcher.patch_artifact(first["patched_artifact_path"], specimen_id="specimen-cand-1", position="center")

    patched_path = Path(second["patched_artifact_path"])
    patched_text = patched_path.read_text(encoding="utf-8")
    assert second["ok"] is True
    assert patched_path == Path(first["patched_artifact_path"])
    assert patched_path.name == "specimen.autoeject.gcode"
    assert "autoeject.autoeject" not in patched_path.name
    assert patched_text.count("atr.bambu.autoejection.v1") == 1
    assert Path(second["manifest_path"]).name == "specimen.autoeject.gcode.manifest.json"


def test_plain_gcode_patch_keeps_bambu_end_homing_before_autoejection_tail(tmp_path: Path) -> None:
    source = tmp_path / "bambu_end_sequence.gcode"
    source.write_text(
        """; generated by Bambu Studio
G90
G1 X82.0 Y82.0 Z0.2 E0.03 F1200
G1 X118.0 Y118.0 Z30.0 E2.50 F1800
M106 S0
; FEATURE: Custom
; MACHINE_END_GCODE_START
M104 S0 ; turn off temperature
G28 X0  ; home X axis
M84     ; disable motors
M73 P100 R0
; EXECUTABLE_BLOCK_END
""",
        encoding="utf-8",
    )
    patcher = BambuGcodeAutoejectionPatcher(output_dir=tmp_path / "patched")

    result = patcher.patch_artifact(source, specimen_id="specimen-cand-1", position="center")

    patched_text = Path(result["patched_artifact_path"]).read_text(encoding="utf-8")
    assert result["ok"] is True
    assert patched_text.index("G28 X0") < patched_text.index("atr.bambu.autoejection.v1")
    assert patched_text.index("atr.bambu.autoejection.end") < patched_text.index("M84")
    assert "BAMBU_AUTOEJECTION_UNEXPECTED_HOME" not in result["validation"]["blockers"]


def test_gcode_3mf_patch_replaces_plate_gcode_and_updates_md5(tmp_path: Path) -> None:
    source = tmp_path / "plate.gcode.3mf"
    original_md5 = hashlib.md5(BASE_GCODE.encode("utf-8")).hexdigest()
    with zipfile.ZipFile(source, "w") as archive:
        archive.writestr("Metadata/plate_1.gcode", BASE_GCODE)
        archive.writestr("Metadata/plate_1.gcode.md5", original_md5)
        archive.writestr("3D/3dmodel.model", "<model />")
    patcher = BambuGcodeAutoejectionPatcher(output_dir=tmp_path / "patched")

    result = patcher.patch_artifact(source, specimen_id="specimen-cand-1", position="left", plate_id=1)

    patched_path = Path(result["patched_artifact_path"])
    assert result["ok"] is True
    assert patched_path.name == "plate.autoeject.gcode.3mf"
    assert result["source_plate_path"] == "Metadata/plate_1.gcode"
    with zipfile.ZipFile(patched_path) as archive:
        patched_gcode = archive.read("Metadata/plate_1.gcode").decode("utf-8")
        patched_md5 = archive.read("Metadata/plate_1.gcode.md5").decode("utf-8").strip()
        assert archive.read("3D/3dmodel.model").decode("utf-8") == "<model />"
    assert patched_gcode.count("atr.bambu.autoejection.v1") == 1
    assert patched_md5 == hashlib.md5(patched_gcode.encode("utf-8")).hexdigest()
    assert result["validation"]["ok"] is True


