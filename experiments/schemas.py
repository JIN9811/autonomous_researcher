"""
File purpose:
- Define the standard Autonomous Experiment Runtime interface.

Key classes/functions:
- ExperimentObjective
- ExperimentCandidate
- ExperimentExecution
- ExperimentEvaluationRequest
- ExperimentEvaluationResult

Inputs/outputs:
- Input: agent-generated specs, operator mode, bridge routing, objective metadata
- Output: typed experiment evaluation records consumed by agents, GUI, logs, and reports

Modification guide:
- Safe places to edit: optional metadata fields and aliases
- Risky places to edit: field names in ExperimentEvaluationResult used by tools/tests
"""

from __future__ import annotations

from datetime import datetime, timezone
from typing import Any, Literal

from pydantic import BaseModel, Field

from utils.ids import make_experiment_id


ObjectiveDirection = Literal["maximize", "minimize", "target"]
ExecutionMode = Literal["test", "live", "virtual", "replay"]
BridgeName = Literal["auto", "virtual", "printer", "robot", "equipment", "analysis"]


def now_iso() -> str:
    """Return UTC timestamp for experiment records."""
    return datetime.now(timezone.utc).isoformat()


class ExperimentObjective(BaseModel):
    """A measurable goal that can be evaluated by test, virtual, or live execution."""

    objective_id: str = "objective-default"
    name: str = "Autonomous experiment objective"
    description: str = ""
    metric_name: str = "objective_score"
    direction: ObjectiveDirection = "maximize"
    target_value: float | None = None
    constraints: dict[str, Any] = Field(default_factory=dict)
    tags: list[str] = Field(default_factory=list)


class ExperimentCandidate(BaseModel):
    """Concrete candidate parameters/specification generated by the current agent stack."""

    candidate_id: str = "candidate-default"
    parameters: dict[str, Any] = Field(default_factory=dict)
    experiment_spec: dict[str, Any] = Field(default_factory=dict)
    source_agent: str = "unknown"

    def merged_parameters(self) -> dict[str, Any]:
        """Return spec values overlaid by explicit candidate parameters."""
        merged = dict(self.experiment_spec)
        merged.update(self.parameters)
        return merged


class ExperimentExecution(BaseModel):
    """How and where the candidate should be evaluated."""

    mode: ExecutionMode = "test"
    bridge: BridgeName = "auto"
    dry_run: bool = True
    allow_physical: bool = False
    requested_tool: str | None = None
    timeout_s: float | None = None


class ExperimentEvaluationRequest(BaseModel):
    """Single standard request passed through the Autonomous Experiment Runtime."""

    run_id: str = ""
    experiment_id: str = Field(default_factory=make_experiment_id)
    session_id: str = ""
    objective: ExperimentObjective = Field(default_factory=ExperimentObjective)
    candidate: ExperimentCandidate = Field(default_factory=ExperimentCandidate)
    execution: ExperimentExecution = Field(default_factory=ExperimentExecution)
    metadata: dict[str, Any] = Field(default_factory=dict)


class ExperimentEvaluationResult(BaseModel):
    """Standard evaluation result returned by all modes and bridges."""

    ok: bool
    tool: str = "experiment.evaluate"
    run_id: str = ""
    experiment_id: str
    session_id: str = ""
    evaluation_id: str
    objective: ExperimentObjective
    candidate_id: str
    mode: str
    bridge: str
    status: str
    objective_score: float | None = None
    metrics: dict[str, Any] = Field(default_factory=dict)
    artifacts: dict[str, Any] = Field(default_factory=dict)
    bridge_result: dict[str, Any] = Field(default_factory=dict)
    job: dict[str, Any] | None = None
    step_trace: list[dict[str, Any]] = Field(default_factory=list)
    failure_code: str | None = None
    created_at: str = Field(default_factory=now_iso)


def request_from_payload(payload: dict[str, Any]) -> ExperimentEvaluationRequest:
    """Normalize loose MCP payloads into the typed runtime request."""
    objective_payload = payload.get("objective") if isinstance(payload.get("objective"), dict) else {}
    candidate_payload = payload.get("candidate") if isinstance(payload.get("candidate"), dict) else {}
    execution_payload = payload.get("execution") if isinstance(payload.get("execution"), dict) else {}
    experiment_spec = payload.get("experiment_spec") if isinstance(payload.get("experiment_spec"), dict) else {}
    parameters = payload.get("parameters") if isinstance(payload.get("parameters"), dict) else {}

    candidate = {
        **candidate_payload,
        "experiment_spec": candidate_payload.get("experiment_spec", experiment_spec),
        "parameters": candidate_payload.get("parameters", parameters),
    }
    if not candidate.get("candidate_id"):
        candidate["candidate_id"] = str(
            experiment_spec.get("candidate_id")
            or parameters.get("candidate_id")
            or payload.get("candidate_id")
            or "candidate-default"
        )

    return ExperimentEvaluationRequest(
        run_id=str(payload.get("run_id", "")),
        experiment_id=str(payload.get("experiment_id") or make_experiment_id()),
        session_id=str(payload.get("session_id", "")),
        objective=ExperimentObjective(**objective_payload),
        candidate=ExperimentCandidate(**candidate),
        execution=ExperimentExecution(**execution_payload),
        metadata=payload.get("metadata") if isinstance(payload.get("metadata"), dict) else {},
    )
